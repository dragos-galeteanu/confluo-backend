package com.confluo.common.security;

/**
 * Enum representing user roles.
 */
public enum UserRole {

    /**
     * Represents a customer role.
     */
    Customer,

    /**
     * Represents a sales role.
     */
    Sales,

    /**
     * Represents an inspector role.
     */
    Inspector,

    /**
     * Represents a support role.
     */
    Support,

    /**
     * Represents an admin role.
     */
    Admin
}
